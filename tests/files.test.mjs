import fs from 'node:fs/promises';
import path from 'node:path';
import { HOME, check, finish } from './helpers.mjs';
import { initDirs } from '../src/main/paths.js';
import { createProject, saveProject } from '../src/main/projects.js';
import { collectFiles, importFile, serveProjectFile } from '../src/main/files.js';
import { makeFixtures } from '../tools/file-types/fixtures.mjs';

await initDirs(HOME);
const sourceDir = path.join(HOME, 'fixtures');
const fixtureDir = path.join(HOME,'file-type-fixtures');
const manifestFile = path.join(fixtureDir,'manifest.json');
const { fixtures } = await fs.readFile(manifestFile,'utf8').then(JSON.parse).catch(() => makeFixtures(fixtureDir));
await fs.mkdir(sourceDir, { recursive: true });
const md = path.join(sourceDir, 'Notes.md');
await fs.writeFile(md, '# Notes\n');
const png = path.join(sourceDir, 'Photo.png');
await fs.copyFile(fixtures.find((f) => f.ext === 'png').path, png);
const project = await createProject({ type: 'file', paths: [md, png] });
const root = project.nodes[project.rootId];
check('file may be root and extra imported files become children', root.kind === 'markdown' && root.children.length === 1);
check('file is copied into project with original name', root.title === 'Notes' && (await fs.stat(path.join(HOME, 'projects', project.id, 'files', root.file))).isFile());
let response = await serveProjectFile(project.id, root.file, new Request('https://wikitree.local/file'));
check('Markdown is served as text', response.headers.get('content-type').startsWith('text/'));
const video = path.join(sourceDir, 'Clip.mp4');
await fs.copyFile(fixtures.find((f) => f.ext === 'mp4').path, video);
const videoBytes = await fs.readFile(video);
const imported = await importFile({ projectId: project.id, path: video });
const videoNodeId = 'testvideo';
project.nodes[videoNodeId] = { id: videoNodeId, ...imported, parent: project.rootId, children: [] };
project.nodes[project.rootId].children.push(videoNodeId);
response = await serveProjectFile(project.id, imported.file, new Request('https://wikitree.local/file', { headers: { range: 'bytes=3-6' } }));
check('video supports range requests for seeking', response.status === 206 && Buffer.from(await response.arrayBuffer()).equals(videoBytes.subarray(3,7)) && response.headers.get('content-range') === `bytes 3-6/${videoBytes.length}`);
await saveProject(project);
await collectFiles(project.id);
check('file collection retains project references', (await fs.readdir(path.join(HOME, 'projects', project.id, 'files'))).length === 3);
await fs.rm(path.join(HOME, 'projects', project.id, 'files', imported.file));
await collectFiles(project.id);
check('file collection removes orphan files', !(await fs.readdir(path.join(HOME, 'projects', project.id, 'files'))).includes(imported.file));
const filesPath = path.join(HOME, 'projects', project.id, 'files');
const photoId = root.children[0];
const photoFile = project.nodes[photoId].file;
delete project.nodes[photoId];
root.children = root.children.filter((c) => c !== photoId);
await saveProject(project);
await fs.writeFile(path.join(filesPath, 'deadbeef.png'), 'never referenced');
await collectFiles(project.id);
const left = await fs.readdir(filesPath);
check('files of deleted nodes stay for history restores; unreferenced files go', left.includes(photoFile) && !left.includes('deadbeef.png'));
await fs.rm(path.join(HOME, 'projects', project.id), { recursive: true, force: true });
finish();
